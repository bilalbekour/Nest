let LANG = localStorage.getItem("nido_locale") || "es";

function t(key) {
  const d = I18N[LANG] || {};
  return d[key] !== undefined ? d[key] : key;
}

function tf(key, ...args) {
  return t(key).replace(/\{(\d+)\}/g, (_, i) => (args[+i] !== undefined ? args[+i] : _));
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.getAttribute("data-i18n")); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  document.querySelectorAll(".langsel").forEach(s => { s.value = LANG; });
  document.title = t("Nido · Reserva de Puestos");
  document.documentElement.lang = LANG;
  if (typeof onI18n === "function") onI18n();
}

